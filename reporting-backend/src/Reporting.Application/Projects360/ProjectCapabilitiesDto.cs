namespace Reporting.Application.Projects360;

/// <summary>
/// **خريطة القدرات الواحدة** (P360-WF-R2 §12): ما يستطيعه المستخدم الحالي على **هذا** المشروع
/// بعينه، محسوبة في الخادم من نفس الحرّاس التي ستحكم الكتابة فعلًا
/// (<see cref="IProject360Authorization.BuildCapabilitiesAsync"/>).
///
/// <para>
/// **مرآة لا مصدر**: <c>false</c> هنا لا يمنع شيئًا، و<c>true</c> لا يمنح شيئًا — المنع والمنح
/// يقعان في الخدمة عند نقطة الكتابة. فائدتها أن تخفي الواجهة ما سيُرفَض بدل أن يكتشف المستخدم
/// الرفض بعد أن يملأ نموذجًا ويضغط حفظ. ولو تناقضت مع الخدمة فالخدمة هي الصادقة والخريطة هي العيب.
/// </para>
///
/// <para>
/// **تُبنى بعد التحقّق من الرؤية دائمًا**: من لا يرى المشروع لا يصل إلى هذه الخريطة أصلًا،
/// فلا تصلح لتعداد المشاريع خارج النطاق.
/// </para>
/// </summary>
/// <param name="CanManageStructure">
/// الكتابة **البنيويّة**: إنشاء/تعديل/حذف الأهداف والمؤشّرات والمخرَجات التعاقديّة
/// والاستراتيجيّة ومسارات العمل.
/// </param>
/// <param name="CanOperate">
/// الكتابة **التشغيليّة** (D-07): التقدّم والحالة والقراءات اليدويّة و**إعادة احتساب الصحّة**.
/// حقل واحد لا حقلان: إعادة الاحتساب تمرّ بنفس حارس
/// <see cref="IProject360Authorization.CanUpdateProject360ProgressAsync"/> حرفيًّا، فإفرادها
/// بعلَم ثانٍ كان سيخلق مصدرين لحقيقة واحدة قابلين للانحراف.
/// </param>
/// <param name="CanWriteGovernance">
/// تسجيل مخاطر/قرارات/ملاحظات إداريّة على المشروع — بدور ورشة الحوكمة لا بملكيّة المشروع،
/// لأنّ الورشة كيان مستقلّ عن Project 360.
/// </param>
public record ProjectCapabilitiesDto(
    bool CanManageStructure,
    bool CanOperate,
    bool CanWriteGovernance);
