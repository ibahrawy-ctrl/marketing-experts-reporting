using Reporting.Domain.Enums;

namespace Reporting.Domain.Projects360;

/// <summary>
/// تقدّم هدف واحد (CPW-R3 · §9-8-ج) — الطبقة الوسطى بين المؤشّر والمشروع في لوحة القيادة.
///
/// <para>
/// **الوزن المُطبَّع لا الخام**: <see cref="NormalizedWeight"/> هو <c>w_i ÷ Σw</c> بعد التطبيع،
/// لأنّ الأوزان الخام **لا يُفرَض** مجموعها 100 (§5-4). عرض الوزن الخام يوهم المدير بنسبة
/// ليست هي المستعملة فعلًا في الاحتساب — فيُعرَض المُطبَّع حصرًا.
/// </para>
///
/// <para>
/// **لا Logic في الواجهة**: الواجهة تتلقّى هذا النموذج جاهزًا فتعرضه؛ لا تجمع أوزانًا ولا تقسم
/// ولا تستنتج حالة. كلّ حساب تمّ على الخادم.
/// </para>
///
/// <para>
/// **عقد الاستعلام الواحد — قرار المالك · ملحق W1-A بند 7 (قيد مُلزِم على W5/W6)**: لوحة قيادة
/// المشروع تُخدَم بـ**استعلام واحد** عبر <c>GET /projects/{id}/overview</c> — لا عشرون استعلامًا،
/// ولا استعلام لكلّ هدف، ولا استعلام لكلّ مؤشّر. تُجلَب الأهداف ومؤشّراتها في **رحلة واحدة**
/// (تحميل مُتضمَّن/إسقاط واحد) ثمّ يُطبَّق <c>ProjectHealthPolicy</c> **في الذاكرة** على النتيجة.
/// </para>
///
/// <para>
/// **لماذا هذا قيد لا توصية؟** لأنّ <c>N+1</c> هنا لا يظهر في التطوير (مشروع بهدفين) بل في
/// التشغيل (مشروع بعشرة أهداف × ستّة مؤشّرات = 60 رحلة). ولأنّ الشكل التجميعيّ لهذا النموذج
/// يُغري بحلقة <c>foreach</c> تستعلم داخلها — وهو بالضبط ما يمنعه هذا البند.
/// </para>
///
/// <para>
/// **حدّ العقد**: الاستعلام الواحد يخصّ **لوحة القيادة** فقط. صفحات التفاصيل (الأهداف، المؤشّرات،
/// المخرجات التعاقديّة، الاستراتيجيّة) لها استعلاماتها **المستقلّة** بترقيم صفحات وفلاتر خاصّة —
/// ولا يجوز حشوها في استعلام اللوحة بحجّة «التوحيد».
/// </para>
/// </summary>
/// <param name="ObjectiveId">الهدف المعنيّ.</param>
/// <param name="Status">الحالة المعلَنة يدويًّا على الهدف (Manual-First — لا تُشتقّ).</param>
/// <param name="NormalizedWeight">الوزن بعد التطبيع 0..1 — أوزان صفريّة كلّها ⟹ توزيع متساوٍ.</param>
/// <param name="KpiScore">نتيجة مؤشّرات هذا الهدف موزونةً — <c>null</c> ⟹ لا مؤشّر محتسَب.</param>
/// <param name="ComputedKpiCount">عدد المؤشّرات التي دخلت الاحتساب فعلًا.</param>
/// <param name="TotalKpiCount">إجماليّ المؤشّرات النشطة تحت الهدف.</param>
public sealed record ProjectObjectiveProgress(
    Guid ObjectiveId,
    ProjectObjectiveStatus Status,
    decimal NormalizedWeight,
    decimal? KpiScore,
    int ComputedKpiCount,
    int TotalKpiCount)
{
    /// <summary>هل ساهم هذا الهدف في نتيجة المشروع؟ (هدف بلا مؤشّر محتسَب لا يسحبها إلى صفر).</summary>
    public bool ContributesToProjectScore => KpiScore is not null;
}
